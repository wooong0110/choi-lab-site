#!/usr/bin/env node
// Import weekly JSON without dropping archived weeks. No network or git operations.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export function validateWeek(data, label) {
  const fail = message => { throw new Error(`${label}: ${message}`); };
  if (!data || !/^\d{4}-\d{2}-\d{2}$/.test(data.date || '') ||
      !Number.isFinite(Date.parse(data.date)) || new Date(data.date).toISOString().slice(0, 10) !== data.date) fail('invalid date');
  if (!Array.isArray(data.papers)) fail('papers must be an array');
  if (data.count !== undefined && data.count !== data.papers.length) fail('count does not match papers');
  if (data.notice !== undefined && typeof data.notice !== 'string') fail('notice must be text');
  const ids = new Set();
  for (const paper of data.papers) {
    if (!paper || typeof paper.title !== 'string' || !paper.title.trim()) fail('paper needs a title');
    if (!Number.isInteger(paper.rating) || paper.rating < 0 || paper.rating > 5) fail('rating must be an integer from 0 to 5');
    for (const key of ['pmid','title','doi','pubmed','journal','year','author','publication_date','online_date','domain','emoji','tldr','question','key_result','why_for_us','limitations','reuse','next_step','type']) {
      if (paper[key] !== undefined && typeof paper[key] !== 'string') fail(`${key} must be text`);
    }
    for (const key of ['what_they_did','concepts']) {
      if (paper[key] !== undefined && (!Array.isArray(paper[key]) || paper[key].some(x => typeof x !== 'string'))) fail(`${key} must be a text array`);
    }
    const id = paper.pmid || paper.doi || paper.title;
    if (ids.has(id)) fail(`duplicate paper ${id}`);
    ids.add(id);
  }
  return { ...data, count: data.papers.length };
}

export function publish({ site, sources = [], dryRun = false }) {
  const dataDir = path.join(site, 'assets', 'data', 'cardnews');
  const read = file => validateWeek(JSON.parse(fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, '')), file);
  const weeks = new Map();
  const filesIn = dir => fs.readdirSync(dir).filter(name => /^\d{4}-\d{2}-\d{2}\.json$/.test(name)).sort().map(name => path.join(dir, name));
  if (fs.existsSync(dataDir)) for (const file of filesIn(dataDir)) { const week = read(file); weeks.set(week.date, week); }
  const incoming = sources.flatMap(source => fs.statSync(source).isDirectory() ? filesIn(source) : [source]);
  for (const file of incoming) { const week = read(file); weeks.set(week.date, week); }
  if (!weeks.size) throw new Error('No weekly JSON found; existing output was not changed.');
  const all = [...weeks.values()].sort((a,b) => b.date.localeCompare(a.date));
  const serialize = value => JSON.stringify(value, null, 2) + '\n';
  const output = '// Generated by scripts/publish-cardnews.mjs. Edit weekly JSON, then rebuild.\nwindow.CARDNEWS = ' + serialize(all).trimEnd() + ';\n';
  const writes = all.map(week => [path.join(dataDir, week.date + '.json'), serialize(week)]);
  writes.push([path.join(site, 'assets', 'js', 'cards-data.js'), output]);
  const changed = writes.filter(([file, body]) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== body);
  // Validate the entire input before any mutation; replace each file atomically.
  if (!dryRun) for (const [file, body] of changed) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file + '.tmp', body, 'utf8');
    fs.renameSync(file + '.tmp', file);
  }
  return { weeks: all.length, papers: all.reduce((n,w) => n + w.papers.length, 0), changed: changed.length, dryRun };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    const dryRun = args.includes('--dry-run');
    const sources = args.filter(arg => arg !== '--dry-run').map(arg => path.resolve(arg));
    const site = fileURLToPath(new URL('../', import.meta.url));
    console.log(JSON.stringify(publish({ site, sources, dryRun })));
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
